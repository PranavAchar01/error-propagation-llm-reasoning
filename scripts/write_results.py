#!/usr/bin/env python3
"""Generate the report's Results section from raw records. No hand-copying.

    python scripts/write_results.py --phase full

Writes paper/results_<phase>.md, which paper/report.md points at. Every number
in the paper therefore comes from results/raw/ by machine — hand-transcribing a
figure from a table into prose is one of the easier ways to publish a wrong
number, and it is entirely avoidable.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from epr.metrics import contamination_flag, load_records, paired_vectors, summarise
from epr.prompts import CONDITIONS
from epr.stats import mcnemar_exact, mde_delta_beta, paired_bootstrap_delta_beta

ROOT = Path(__file__).resolve().parents[1]

PREDICTED_DELTA = 0.15  # HYPOTHESIS.md H1


def pct(x, n=None):
    if x is None:
        return "--"
    return f"{100 * x:.1f}%" + (f" (n={n})" if n is not None else "")


def num(x, fmt="{:+.3f}"):
    return "--" if x is None else fmt.format(x)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", default="full")
    ap.add_argument("--bootstrap", type=int, default=10_000)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    records = load_records(args.phase)
    if not records:
        print(f"no records for phase {args.phase}")
        return 1

    s = summarise(records)
    model = next(iter(s.values())).model
    seeds = sorted({r["seed"] for r in records})
    L: list[str] = []

    L += [
        f"<!-- GENERATED by scripts/write_results.py --phase {args.phase}. Do not edit by hand. -->",
        "",
        "## 3. Results",
        "",
        (
            f"Model `{model}`; seeds {seeds}; {len(records):,} raw records in "
            f"`results/raw/{args.phase}/`. Every figure below is regenerated from "
            "those records by `make reproduce`, with no network access."
        ),
        "",
    ]

    # --- 3.1 manipulation check -------------------------------------------
    L += ["### 3.1 Manipulation check", ""]
    for ds in sorted({d for d, _ in s}):
        d0 = s.get((ds, "direct_zs"))
        c0 = s.get((ds, "cot_fs"))
        if not (d0 and c0):
            continue
        gap = (c0.accuracy - d0.accuracy) * 100 if (c0.accuracy and d0.accuracy) else float("nan")
        # Three outcomes, not two. Collapsing them would let a condition where
        # chain-of-thought actively HURT be reported as "holds".
        if gap < 2 and (d0.accuracy or 0) >= 0.95:
            verdict = (
                "**FAILS (ceiling)** — no headroom for reasoning to help, so this "
                "dataset cannot support a depth-slope measurement"
            )
        elif gap <= -2:
            verdict = (
                "**FAILS (inverted)** — chain-of-thought is *worse* than answering "
                "directly. Elaborating a chain introduces errors the direct answer "
                "avoids, which is itself a result about this model on this task"
            )
        elif gap < 2:
            verdict = "**inconclusive** — chain-of-thought neither helps nor hurts materially"
        else:
            verdict = "holds — chain-of-thought improves accuracy as expected"
        L.append(
            f"- **{ds}**: `direct_zs` {pct(d0.accuracy, d0.n)} vs `cot_fs` "
            f"{pct(c0.accuracy, c0.n)} — gap {gap:+.1f} points. {verdict}."
        )
    L += [""]

    # --- 3.2 per-condition table ------------------------------------------
    L += [
        "### 3.2 All conditions",
        "",
        (
            "`--` means not measurable for that dataset (FOLIO and BBH ship no gold "
            "proof chain), never zero."
        ),
        "",
        (
            "| dataset | condition | n | accuracy [95% CI] | first-attempt | β_depth | "
            "first-error pos | post-error recovery | verifier reject | parse fail |"
        ),
        "|" + "---|" * 10,
    ]
    for ds in sorted({d for d, _ in s}):
        for cond in CONDITIONS:
            c = s.get((ds, cond))
            if not c:
                continue
            lo, hi = c.accuracy_ci
            L.append(
                f"| {ds} | `{cond}` | {c.n} | {pct(c.accuracy)} [{pct(lo)}, {pct(hi)}] | "
                f"{pct(c.first_attempt_accuracy)} | {num(c.beta_depth)} | "
                f"{num(c.mean_first_error_position, '{:.2f}')} | "
                f"{pct(c.recovery_rate, c.n_with_error)} | "
                f"{pct(c.verifier_rejection_rate, c.n_steps_total)} | "
                f"{pct(c.parse_failure_rate, c.n_with_steps)} |"
            )
    L += [""]

    # --- 3.3 depth ---------------------------------------------------------
    L += ["### 3.3 Accuracy by ground-truth proof depth", ""]
    for ds in sorted({d for d, _ in s}):
        conds = [(c, s[(ds, c)]) for c in CONDITIONS if (ds, c) in s and s[(ds, c)].depths]
        if not conds:
            continue
        depths = sorted({d for _, c in conds for d in c.depths})
        L += [
            f"**{ds}**",
            "",
            "| condition | " + " | ".join(f"d={d}" for d in depths) + " | β_depth |",
            "|" + "---|" * (len(depths) + 2),
        ]
        for name, c in conds:
            byd = c.accuracy_by_depth()
            cells = [
                f"{100 * byd[d][0] / byd[d][1]:.0f}% ({byd[d][0]}/{byd[d][1]})"
                if d in byd
                else "--"
                for d in depths
            ]
            L.append(f"| `{name}` | " + " | ".join(cells) + f" | {num(c.beta_depth)} |")
        L += [""]

    # --- 3.4 confirmatory --------------------------------------------------
    L += ["### 3.4 Pre-registered confirmatory tests", ""]
    tests = [
        ("C1", "prontoqa", "delta_beta", "primary"),
        ("C2", "proofwriter", "delta_beta", "confirmatory"),
        ("C3", "prontoqa", "accuracy", "confirmatory"),
    ]
    for tag, ds, kind, role in tests:
        depth, ca, cb, uids = paired_vectors(records, "struct_verify", "cot_fs", ds)
        if len(uids) == 0:
            L += [f"- **{tag}** ({ds}, {role}): no paired items — not run.", ""]
            continue
        # An instrument with no accuracy gradient cannot yield a slope. Say so
        # explicitly rather than printing a meaningless number with a CI.
        base = s.get((ds, "direct_zs"))
        saturated = base is not None and (base.accuracy or 0) >= 0.95
        if kind == "delta_beta":
            r = paired_bootstrap_delta_beta(depth, ca, cb, args.bootstrap, args.seed)
            flag = (
                "  **NOT ESTIMABLE — the instrument is at ceiling "
                f"(`direct_zs` {pct(base.accuracy)}), so β_depth ≈ 0 in every condition "
                "and this number carries no information.**"
                if saturated
                else ""
            )
            L += [
                f"- **{tag}** ({ds}, Δβ `struct_verify` − `cot_fs`, {role}): {r.fmt()}.{flag}",
                "",
            ]
        else:
            b, c, p = mcnemar_exact(ca, cb)
            delta = (ca.mean() - cb.mean()) * 100 if len(ca) else float("nan")
            flag = "  (at ceiling; uninformative)" if saturated else ""
            L.append(
                f"- **{tag}** ({ds}, accuracy `struct_verify` − `cot_fs`, {role}): "
                f"{delta:+.1f} points, exact McNemar b={b} c={c}, p={p:.4f}, n={len(ca)}.{flag}"
            )
            L.append("")

    # --- 3.5 power ---------------------------------------------------------
    L += ["### 3.5 Power: no effect, or too little data to see one?", ""]
    for ds in ("prontoqa", "proofwriter"):
        depth, ca, cb, uids = paired_vectors(records, "struct_verify", "cot_fs", ds)
        if len(uids) < 20:
            L += [f"- **{ds}**: only {len(uids)} paired items — power not estimated.", ""]
            continue
        mde = mde_delta_beta(depth, cb, seed=args.seed)
        if mde == float("inf"):
            claim = (
                "**no effect in the searched range (Δβ ≤ 2.0) is detectable at 80% "
                "power.** Any non-significant result here is uninformative, not evidence "
                "of absence."
            )
        elif mde > PREDICTED_DELTA:
            claim = (
                f"the smallest detectable Δβ is **{mde:+.2f}**, larger than the "
                f"pre-registered prediction of {PREDICTED_DELTA:+.2f}. The study is "
                "**underpowered for its own primary hypothesis**; a null here means "
                "'could not see it', not 'it is not there'."
            )
        else:
            claim = (
                f"the smallest detectable Δβ is **{mde:+.2f}**, at or below the "
                f"pre-registered {PREDICTED_DELTA:+.2f}, so a null is informative."
            )
        L += [f"- **{ds}** (n={len(uids)} paired items): {claim}", ""]

    # --- 3.6 health --------------------------------------------------------
    flags = [f for c in s.values() if (f := contamination_flag(c))]
    L += ["### 3.6 Instrument and run health", ""]
    L += [f"- {f}" for f in flags] if flags else ["- No direct-answer baseline reached 95%."]
    errs = sum(c.n_api_error for c in s.values())
    unp = sum(c.n_unparsed_answer for c in s.values())
    tot = sum(c.n for c in s.values())
    L += [
        (
            f"- API calls failing after retries, excluded from all denominators: "
            f"**{errs}** of {tot + errs:,}."
        ),
        f"- Responses with no parseable ANSWER line, scored incorrect: **{unp}**.",
        "",
    ]

    out = ROOT / "paper" / f"results_{args.phase}.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\n[write_results] wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
